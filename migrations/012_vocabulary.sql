create table if not exists vocabulary (
  id            uuid primary key default gen_random_uuid(),
  word          text    not null,
  level         integer not null,                 -- 1-6 (TOPIK 급수)
  pos           text,                             -- 명사/동사/형용사/부사/관형사/관용구/속담
  theme         text,                             -- 의식주/직업/사회 등
  meaning       text    not null,
  example       text,
  pronunciation text,                             -- 표준 발음 (표기와 다를 때)
  frequency     integer,                          -- 상대 빈도 (높을수록 자주 쓰임)
  hanja         text,                             -- 한자어의 한자 (고유어는 NULL)
  created_at    timestamptz not null default now()
);
create index if not exists idx_vocabulary_level on vocabulary (level);
create index if not exists idx_vocabulary_theme on vocabulary (theme);
create unique index if not exists uq_vocabulary_word_level on vocabulary (word, level);

