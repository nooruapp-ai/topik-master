do $$
begin
  if to_regclass('public.problem_types') is not null then
    update problems set type_id = (
      select id from problem_types
      where level='topik1' and category='grammar' and type_number=1
      limit 1)
    where category='grammar' and level in (1,2) and created_by='admin'
      and question in (
        '동생은 채소는 안 먹고 고기___ 먹어요.',
